#!/usr/bin/env bash
# Start the LOCAL staging BOINC server (http://127.0.0.1:8888/nuclear), built on the official
# boinc-server-docker. Staging only: test signing key, PostgreSQL without a password, nothing
# reachable from outside this machine. See server/staging/README.md.
#
# Usage: bash server/staging/up.sh [path to boinc-server-docker checkout]
set -euo pipefail
repo="$(cd "$(dirname "$0")/../.." && pwd)"
upstream="${1:-$HOME/nah-staging/boinc-server-docker}"
# Address volunteers reach staging at: 127.0.0.1 (this computer only) or this computer's LAN address
# (other PCs on your home network). Never a public address: staging uses a test signing key.
host="${STAGING_HOST:-127.0.0.1}"

wrapper="$repo/client/app_version/wrapper_26018_x86_64-pc-linux-gnu"
if [ ! -f "$wrapper" ]; then
  curl -fsSL https://boinc.berkeley.edu/dl/wrapper_26018_x86_64-pc-linux-gnu -o "$wrapper"
fi
echo "d75a1bfa451d57ee6c2a7e42a74bbb23a8d21194184681a477744a028a1ebd3b  $wrapper" | sha256sum -c -
chmod 0755 "$wrapper"
test -x "$repo/client/app_version/lmp_nah_stable_29Aug2024" || { echo "build LAMMPS first: bash client/build_lammps.sh" >&2; exit 1; }

# Bind the web port to $host only (replaces the upstream "80:80" or an earlier binding).
sed -i -E 's,^      - "(80|[0-9.]+:8888):80".*,      - "'"$host"':8888:80"   # staging: this address only,' "$upstream/docker-compose.yml"
cat > "$upstream/docker-compose.override.yml" <<YML
# Generated by nuclear-at-home/server/staging/up.sh
services:
  makeproject:
    volumes: ["$repo:/opt/nuclear-at-home:ro"]
  mysql:
    restart: unless-stopped
  apache:
    restart: unless-stopped   # come back after a reboot (then re-run up.sh if Python is missing)
    ports: ["127.0.0.1:8888:80"]   # this computer too, so a local client attached at 127.0.0.1 keeps working
    environment:
      - NAH_PG_DSN=host=postgres dbname=nuclear user=postgres
      - NAH_SCIENCE_DIR=/srv/nuclear/science
      - NAH_BOINC_PROJECT_DIR=/home/boincadm/project
      - NAH_PYTHON=/opt/py312/bin/python3
    volumes:
      - "$repo:/opt/nuclear-at-home:ro"
      - "science:/srv/nuclear/science"
  postgres:
    image: postgres:16-alpine
    restart: unless-stopped
    environment: [POSTGRES_DB=nuclear, POSTGRES_HOST_AUTH_METHOD=trust]   # staging only
    ports: ["127.0.0.1:5433:5432"]
    volumes: ["pgdata:/var/lib/postgresql/data"]
volumes:
  science:
  pgdata:
YML

cd "$upstream"
export URL_BASE="http://$host:8888" PROJECT=nuclear
docker compose up -d
# Python 3.12 for our scripts: the published images are Debian stretch (Python 3.5, archived apt),
# so staging uses a pinned standalone CPython plus the pinned wheels. Repeated after a re-create.
py=cpython-3.12.16+20261026-x86_64-unknown-linux-gnu-install_only.tar.gz
docker compose exec -T -u root apache bash -c "test -x /opt/py312/bin/python3 || (cd /tmp \
  && curl -fsSL -o py.tgz https://github.com/astral-sh/python-build-standalone/releases/download/20261026/${py//+/%2B} \
  && echo '6a79e922e50006b601f29e688407659da1c2b86ebcd4e9c7254cf234be8b89de  py.tgz' | sha256sum -c - \
  && tar -xzf py.tgz -C /opt && mv /opt/python /opt/py312 && rm py.tgz \
  && /opt/py312/bin/python3 -m pip install -q --no-cache-dir -r /opt/nuclear-at-home/requirements-server.txt); \
  mkdir -p /srv/nuclear/science && chown 1000:1000 /srv/nuclear/science"
# App, templates, daemons; signed by the makeproject container (staging key).
docker compose run --rm -T makeproject bash /opt/nuclear-at-home/server/staging/install_app.sh
# Our wrappers read their environment from bin/nah.env, because BOINC's cron restarts daemons without it.
docker compose exec -T -u boincadm apache bash -c 'for v in NAH_PYTHON NAH_PG_DSN NAH_SCIENCE_DIR NAH_BOINC_PROJECT_DIR; do
  printf "export %s=%q\n" $v "${!v}"; done > $PROJECT_ROOT/bin/nah.env && chmod 600 $PROJECT_ROOT/bin/nah.env'
# BOINC stores the download/upload address inside each work unit, result and app version when they
# are created. After an address change, point unfinished ones at the current address, or other
# computers fetch from the old one (127.0.0.1 is the volunteer's own PC) and stall. Signatures
# cover file contents, not addresses, so they stay valid.
docker compose exec -T mysql mysql nuclear -e "
UPDATE workunit SET xml_doc = REGEXP_REPLACE(xml_doc, 'http://[0-9.]+:8888/', 'http://$host:8888/') WHERE assimilate_state < 2;
UPDATE result SET xml_doc_in = REGEXP_REPLACE(xml_doc_in, 'http://[0-9.]+:8888/', 'http://$host:8888/') WHERE server_state < 5;
UPDATE app_version SET xml_doc = REGEXP_REPLACE(xml_doc, 'http://[0-9.]+:8888/', 'http://$host:8888/');"
# Restart the daemons after the rewrite: the feeder caches app versions and work.
docker compose exec -T -u boincadm apache bash -c 'cd $PROJECT_ROOT && bin/stop && bin/start'
for _ in $(seq 30); do docker compose exec -T postgres pg_isready -U postgres -q && break; sleep 2; done
if ! docker compose exec -T postgres psql -U postgres -d nuclear -tAc "select 1 from pg_tables where tablename='wu_results'" | grep -q 1; then
  docker compose exec -T postgres psql -q -U postgres -d nuclear -v ON_ERROR_STOP=1 < "$repo/stats/schema.sql"
fi
echo "Staging BOINC server: http://$host:8888/nuclear  (PostgreSQL on 127.0.0.1:5433)"
